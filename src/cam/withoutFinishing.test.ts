import { expect, it } from 'vitest'
import fixture from './fixtures/legacy-breakthrough.json'
import originalFinishFixture from './fixtures/legacy-breakthrough-original-finishing.json'
import { withoutFinishing } from './withoutFinishing'
import { createPartFromGCode } from '../gcode/importPart'
import { simulateGCode } from '../gcode/simulator'
import { generateCam } from './generate'
import { readDxf } from './dxf'
import { defaultProgramSettings } from '../gcode/programSettings'
import { selectMaterialParts } from '../gcode/materialSelection'

const profile = '12-2pass-2mm-depth12p4'
const part = () => createPartFromGCode('shelf.nc', fixture.gcode, fixture.dxf)

it('regenerates pre-ramp-change saved NC without finishing, using the current ramp while preserving cutting depths', () => {
  // Fixture generated by the pre-af6fdcc CAM implementation, not the compatibility path.
  const source = part()
  const result = withoutFinishing(source, profile)
  expect(source.gcode).toBe(fixture.gcode)
  expect(result.gcode).toContain('(Ramp 5 degrees F1200 / cutting F3000')
  expect(result.gcode).toContain('/ cutter 6 mm')
  expect(result.gcode).toContain('(Pass depth 6.2 mm)')
  expect(result.gcode).toContain('(Pass depth 12.4 mm)')
  expect(result.gcode).toContain('G01 Z-2 F600')
  expect(result.gcode).not.toContain('(Finishing pass:')
  expect(result.gcode).toContain('(Roughing: leave 0 mm on walls)')
  expect(result.gcode).toContain('(Tab 4)')
  const simulation = simulateGCode(result.gcode)
  expect(simulation.errors).toEqual([])
  expect(simulation.deepestCutMm).toBe(12.4)
  expect(withoutFinishing(source, profile)).toBe(result)
})

it('selects legacy saved variants for skip-finishing jobs', () => {
  const source = part()
  source.metadata.materialVariants = { version: 1, primaryProfile: profile, profiles: {
    [profile]: { gcode: fixture.gcode, errors: [], warnings: [] },
  } } as never
  const result = selectMaterialParts([source], { materialProfile: profile, skipFinishingPass: true, instances: [{ partId: source.id }] })
  expect(result.errors).toEqual([])
  expect(result.parts[0].gcode).not.toContain('(Finishing pass:')
})

it('keeps the new ramp preset for newly generated programs', () => {
  const generated = generateCam(readDxf(fixture.dxf, 'mm'), { thickness: 12, profilePasses: 2, drillDepthMm: 2, units: 'mm', operations: {} })
  expect(generated.errors).toEqual([])
  const result = withoutFinishing(createPartFromGCode('new.nc', generated.gcode, fixture.dxf), profile)
  expect(result.gcode).toContain('(Ramp 5 degrees F1200 / cutting F3000')
})

it.each([
  (code: string) => code.replaceAll('F3000', 'F2700'),
  (code: string) => code.replaceAll('Z-12.4 ', 'Z-12.6 '),
  (code: string) => code.replace('G01 X', 'G01 X9'),
])('still rejects edited historical machining', edit => {
  expect(() => withoutFinishing({ ...part(), gcode: edit(fixture.gcode) }, profile)).toThrow('could not be reproduced')
})

it('rejects different cutters even when only the saved header differs', () => {
  expect(() => withoutFinishing({ ...part(), gcode: fixture.gcode.replace('cutter 6 mm', 'cutter 6.35 mm') }, profile)).toThrow('6 mm cutter')
})


it('exports V2 sheets using legacy components with finishing skipped', async () => {
  const { autoNest } = await import('../nesting/nestingEngine')
  const { exportCombinedGCode } = await import('../gcode/exporter')
  const parts = [part(), part()]
  for (const source of parts) source.metadata.materialVariants = { version: 1, primaryProfile: profile, profiles: {
    [profile]: { gcode: fixture.gcode, errors: [], warnings: [] },
  } } as never
  const sheet: import('../models/Sheet').Sheet = {
    gcodeSettings: { ...defaultProgramSettings, safeZ: 20 },
    name: 'Legacy shelf', nestingMethod: 'v2', width: 1200, height: 1200, spacing: 30, borderSpacing: 22,
    materialProfile: profile, skipFinishingPass: true, screwMarkingEnabled: false,
    instances: parts.map((source, index) => ({ id: `i${index}`, partId: source.id, x: 22, y: 22, sheetIndex: 0, rotation: 0, locked: false })),
  }
  sheet.instances = autoNest(parts, sheet)
  const output = exportCombinedGCode(parts, sheet)
  expect(output.errors).toEqual([])
  expect(simulateGCode(output.gcode).deepestCutMm).toBe(12.4)
  expect(output.gcode).not.toContain('(Finishing pass:')
  expect(simulateGCode(output.gcode).errors).toEqual([])
})

// Captured saved tray component: both the original 3-degree ramp and F3000 finish.
it('accepts historical FAST machining with the original finishing feed', () => {
  const source = createPartFromGCode('tray.nc', originalFinishFixture.gcode, originalFinishFixture.dxf)
  const result = withoutFinishing(source, profile)
  expect(result.gcode).toContain('(Ramp 5 degrees F1200 / cutting F3000')
  expect(result.gcode).toContain('(Roughing: leave 0 mm on walls)')
  expect(result.gcode).not.toContain('(Finishing pass:')
  expect(result.gcode).toContain('(Tab 4)')
  expect(simulateGCode(result.gcode).errors).toEqual([])
  expect(simulateGCode(result.gcode).deepestCutMm).toBe(12.4)
  expect(source.gcode).toBe(originalFinishFixture.gcode)
})

it('accepts the current ramp with the historical finishing feed', () => {
  const generated = generateCam(readDxf(fixture.dxf, 'mm'), { thickness: 12, profilePasses: 2, drillDepthMm: 2, finishingFeedMultiplier: 1, units: 'mm', operations: {} })
  expect(generated.errors).toEqual([])
  expect(() => withoutFinishing(createPartFromGCode('new-ramp.nc', generated.gcode, fixture.dxf), profile)).not.toThrow()
})

it.each([
  (code: string) => code.replace('F3000', 'F2700'),
  (code: string) => code.replaceAll('Z-12.4 ', 'Z-12.6 '),
  (code: string) => code.replace('G01 X', 'G01 X9'),
])('rejects modified historical programs even with the original finishing feed', edit => {
  const source = createPartFromGCode('edited.nc', edit(originalFinishFixture.gcode), originalFinishFixture.dxf)
  expect(() => withoutFinishing(source, profile)).toThrow('could not be reproduced')
})
